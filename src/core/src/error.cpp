std::string HrToString(long hr) {
    char buf[320];
    const unsigned long code = static_cast<unsigned long>(hr);
    for (const HrName& entry : kHrNames) {
        if (entry.hr == hr) {
            std::snprintf(buf, sizeof(buf), "0x%08lX (%s)", code, entry.name);
            return std::string(buf);
        }
    }
    char text[256] = {};
    DWORD len = FormatMessageA(FORMAT_MESSAGE_FROM_SYSTEM | FORMAT_MESSAGE_IGNORE_INSERTS, nullptr, code,
                               MAKELANGID(LANG_ENGLISH, SUBLANG_ENGLISH_US), text, sizeof(text), nullptr);
    if (len == 0)
        len = FormatMessageA(FORMAT_MESSAGE_FROM_SYSTEM | FORMAT_MESSAGE_IGNORE_INSERTS, nullptr, code, 0, text,
                             sizeof(text), nullptr);
    while (len > 0 && (text[len - 1] == '\r' || text[len - 1] == '\n' || text[len - 1] == ' ' || text[len - 1] == '.'))
        text[--len] = '\0';
    std::snprintf(buf, sizeof(buf), "0x%08lX (%s)", code, len > 0 ? text : "unknown");
    return std::string(buf);
}

void LogHr(long hr, const char* expr, const char* file, int line) {
    Log::Write(LogLevel::Error, "hr", file, line, "%s failed: %s", expr ? expr : "?", HrToString(hr).c_str());
}

